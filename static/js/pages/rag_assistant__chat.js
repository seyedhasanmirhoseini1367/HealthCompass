async function sendMessage() {
  const input = document.getElementById('msgInput');
  const msg = input.value.trim();
  if (!msg) return;

  const btn = document.getElementById('sendBtn');
  btn.disabled = true;
  const stopBtn = document.getElementById('stopBtn');
  _chatAbort = new AbortController();
  if (stopBtn) { stopBtn.hidden = false; }
  let failed = false;
  input.value = '';
  input.style.height = 'auto';

  // Hide empty state
  const empty = document.getElementById('emptyState');
  if (empty) empty.style.display = 'none';

  const area = document.getElementById('messagesArea');
  area.appendChild(makeBubble('user', msg));

  // Re-append typing indicator AFTER the user bubble so dots appear below it
  const typing = document.getElementById('typingIndicator');
  area.appendChild(typing);
  typing.style.display = 'flex';
  _autoScroll = true;
  scrollToBottom(true);

  // Create the assistant bubble up-front so tokens stream into it
  const assistantWrap = makeAssistantBubble('', []);
  const contentDiv    = assistantWrap.querySelector('.md-content');
  const rawBuf        = [];   // collects raw text for copy & markdown re-render

  let firstToken = true;

  // Whose records to answer from. The server re-checks this on every request;
  // sending it here only saves the user re-stating it.
  const picker  = document.getElementById('subjectSelect');
  const subject = picker ? picker.value : 'self';

  try {
    // "Everyone" produces one labelled answer per person, which is not a
    // shape a single token stream can carry — so it takes the non-streaming
    // endpoint instead of silently streaming just one of them.
    if (subject === 'all') {
      const r = await fetch(ASK_URL, {
        method: 'POST',
        signal: _chatAbort.signal,
        headers: { 'Content-Type': 'application/json', 'X-CSRFToken': CSRF },
        body: JSON.stringify({ message: msg, session_id: SESSION_ID, subject: subject }),
      });
      if (!r.ok) throw new Error(`HTTP ${r.status}`);
      const data = await r.json();
      typing.style.display = 'none';
      if (firstToken) { area.appendChild(assistantWrap); firstToken = false; }
      rawBuf.push(data.response || '');
      contentDiv.innerHTML = renderMarkdown(rawBuf.join(''));
      if (data.sources) renderSources(assistantWrap, data.sources);
      // Same bookkeeping the stream's 'done' event does, so the copy button
      // works identically on a multi-person answer.
      assistantWrap.querySelector('.bubble-assistant')
                   .setAttribute('data-raw', rawBuf.join(''));
      scrollToBottom();
      return;
    }

    const resp = await fetch(STREAM_URL, {
      method: 'POST',
      signal: _chatAbort.signal,
      headers: { 'Content-Type': 'application/json', 'X-CSRFToken': CSRF },
      body: JSON.stringify({ message: msg, session_id: SESSION_ID, subject: subject }),
    });

    if (!resp.ok) throw new Error(`HTTP ${resp.status}`);

    const reader  = resp.body.getReader();
    const decoder = new TextDecoder();
    let renderPending = false;
    let   buf     = '';

    while (true) {
      const { done, value } = await reader.read();
      if (done) break;

      buf += decoder.decode(value, { stream: true });

      // SSE lines are separated by double newline
      const lines = buf.split('\n\n');
      buf = lines.pop();   // keep incomplete tail

      for (const block of lines) {
        const line = block.trim();
        if (!line.startsWith('data: ')) continue;
        let payload;
        try { payload = JSON.parse(line.slice(6)); } catch { continue; }

        if (payload.type === 'token') {
          if (firstToken) {
            typing.style.display = 'none';
            area.appendChild(assistantWrap);
            firstToken = false;
          }
          rawBuf.push(payload.content);
          // Re-render at most once per animation frame: parsing the whole
          // answer as markdown on every token was quadratic on long answers.
          if (!renderPending) {
            renderPending = true;
            requestAnimationFrame(function () {
              renderPending = false;
              contentDiv.innerHTML = renderMarkdown(rawBuf.join(''));
              scrollToBottom();
            });
          }

        } else if (payload.type === 'sources') {
          renderSources(assistantWrap, payload.sources || []);

        } else if (payload.type === 'chart') {
          renderChart(assistantWrap, payload.chart);

        } else if (payload.type === 'chart_unavailable') {
          renderChartUnavailable(assistantWrap, payload.reason);

        } else if (payload.type === 'meta') {
          renderModeBadge(assistantWrap, payload.mode || 'personal');
          if (payload.mode === 'consent_required') {
            renderConsentAction(assistantWrap, payload.consent_url);
          }

        } else if (payload.type === 'error') {
          typing.style.display = 'none';
          if (firstToken) area.appendChild(assistantWrap);
          rawBuf.push(payload.message || 'An error occurred.');
          contentDiv.innerHTML = renderMarkdown(rawBuf.join(''));
          firstToken = false;
          failed = true;

        } else if (payload.type === 'done') {
          // Final render (the per-frame one may still be pending) and the raw
          // text for the copy button.
          contentDiv.innerHTML = renderMarkdown(rawBuf.join(''));
          assistantWrap.querySelector('.bubble-assistant').setAttribute('data-raw', rawBuf.join(''));
        }
      }
    }

  } catch(err) {
    typing.style.display = 'none';
    failed = true;
    const stopped = err && err.name === 'AbortError';
    if (firstToken) {
      area.appendChild(makeAssistantBubble(stopped ? 'Stopped.' : 'Network error. Please check your connection.', []));
      firstToken = false;
    } else if (stopped) {
      contentDiv.innerHTML = renderMarkdown(rawBuf.join('') + '\n\n*Stopped.*');
    }
  } finally {
    typing.style.display = 'none';
    if (firstToken) {
      area.appendChild(makeAssistantBubble('Sorry, I couldn\'t get a response. Please try again.', []));
      failed = true;
    }
    if (failed) { addRetry(area.lastElementChild, msg); }
    btn.disabled = false;
    if (stopBtn) { stopBtn.hidden = true; }
    _chatAbort = null;
    scrollToBottom();
  }
}

function makeBubble(role, text) {
  const wrap = document.createElement('div');
  wrap.className = `msg-${role}`;
  const bubble = document.createElement('div');
  bubble.className = `bubble bubble-${role}`;
  bubble.textContent = text;
  wrap.appendChild(bubble);
  const time = document.createElement('div');
  time.className = 'msg-time';
  time.textContent = new Date().toLocaleTimeString('en', {hour:'2-digit', minute:'2-digit'});
  wrap.appendChild(time);
  return wrap;
}

function makeAssistantBubble(text, sources) {
  const wrap = document.createElement('div');
  wrap.className = 'msg-assistant';

  const bubble = document.createElement('div');
  bubble.className = 'bubble bubble-assistant';
  bubble.setAttribute('data-raw', text);

  const copyBtn = document.createElement('button');
  copyBtn.className = 'copy-btn';
  copyBtn.setAttribute('aria-label', 'Copy message');
  copyBtn.innerHTML = hcIcon('copy');
  copyBtn.onclick = function() { copyMsg(this); };

  const content = document.createElement('div');
  content.className = 'md-content';
  if (text) content.innerHTML = renderMarkdown(text);

  bubble.appendChild(copyBtn);
  bubble.appendChild(content);
  wrap.appendChild(bubble);

  // Placeholder sources row — filled later by renderSources()
  const sourcesRow = document.createElement('div');
  sourcesRow.className = 'sources-row';
  wrap.appendChild(sourcesRow);

  if (sources && sources.length) {
    renderSources(wrap, sources);
  }

  const time = document.createElement('div');
  time.className = 'msg-time';
  time.textContent = new Date().toLocaleTimeString('en', {hour:'2-digit', minute:'2-digit'});
  wrap.appendChild(time);
  return wrap;
}

function renderSources(wrap, sources) {
  if (!sources || !sources.length) return;
  const row = wrap.querySelector('.sources-row');
  if (!row) return;
  row.innerHTML = '';
  sources.forEach(s => {
    const chip = document.createElement('span');
    if (s.is_general) {
      // Mirrors the personal branch below: DOM construction, never innerHTML.
      // This branch previously interpolated s.source_url into an href and
      // s.source_name into element content unescaped. Knowledge-base rows are
      // admin-controlled today, so the present risk was low — but `javascript:`
      // URLs and quote-breakout both worked, and the inconsistency between two
      // adjacent branches is how that becomes exploitable the day the knowledge
      // base ingests an external feed.
      chip.className = 'source-chip general';
      const label = `🔗 ${(s.source_name || s.title || 'Source').substring(0, 30)}`;

      // Only http(s) may become a link. Anything else renders as plain text, so
      // a javascript: or data: URL cannot survive as a clickable target.
      // Same rule as the markdown link renderer — one implementation, so the
      // two cannot drift into disagreeing about what is safe.
      const safeHref = safeUrl(s.source_url);

      if (safeHref) {
        const link = document.createElement('a');
        link.href = safeHref;
        link.target = '_blank';
        link.rel = 'noopener';
        link.textContent = label;
        chip.appendChild(link);
      } else {
        chip.textContent = label;
      }
    } else {
      chip.className = 'source-chip';
      const link = document.createElement('a');
      link.href = s.record_id ? `/records/${s.record_id}/` : '#';
      link.style.color = 'inherit';
      link.textContent = `📎 ${(s.title || 'Record').substring(0, 25)}`;
      chip.appendChild(link);
    }
    row.appendChild(chip);
  });
}

function renderModeBadge(wrap, mode) {
  const labels = {
    personal:   ['🔒 Your records', 'personal'],
    general:    ['🌐 General knowledge', 'general'],
    hybrid:     ['✨ Records + Guidelines', 'hybrid'],
    trajectory: ['📈 Health trend', 'trajectory'],
    emergency:  ['🚨 Emergency', 'personal'],
  };
  const [label, cls] = labels[mode] || ['', 'personal'];
  if (!label) return;
  const existing = wrap.querySelector('.mode-badge');
  if (existing) return;
  const badge = document.createElement('div');
  badge.className = `mode-badge ${cls}`;
  badge.textContent = label;
  const sourcesRow = wrap.querySelector('.sources-row');
  if (sourcesRow) wrap.insertBefore(badge, sourcesRow);
}

// The assistant refuses without consent and used to name "Privacy & Consent
// settings" in prose, with no link — and the page had none anywhere in the UI
// either, so the refusal was a dead end. Consent is a control the patient is
// entitled to exercise, so the refusal carries the way to exercise it.
function renderConsentAction(wrap, url) {
  if (wrap.querySelector('.consent-action')) return;

  // Same-origin only. The URL arrives over the wire, and an absolute or
  // scheme-relative one would turn this into an open redirect on a button the
  // patient is being told to trust — so this is the same rule as everywhere
  // else in this file, with the stricter option applied.
  const href = safeUrl(url, true) || '/accounts/consent/';

  const row = document.createElement('div');
  row.className = 'consent-action';
  row.style.cssText = 'margin-top:.75rem';

  const link = document.createElement('a');
  link.href = href;
  link.className = 'btn btn-primary';
  link.style.cssText = 'font-size:.82rem;padding:.42rem .9rem';
  link.textContent = 'Open Privacy & Consent settings';

  row.appendChild(link);
  const sourcesRow = wrap.querySelector('.sources-row');
  if (sourcesRow) wrap.insertBefore(row, sourcesRow); else wrap.appendChild(row);
}


// Why no chart, when one was asked for.
//
// Nothing used to be rendered in this case while the system prompt separately
// told the model to say "Here is your chart:" — so the patient was promised a
// chart, shown nothing, and left to guess which half had broken.
//
// textContent rather than innerHTML for the same reason renderChart uses it:
// the reason can name a biomarker that came from an uploaded document, and
// there is no escaping anywhere in that chain.
function renderChartUnavailable(wrap, reason) {
  if (!reason) return;
  const note = document.createElement('div');
  note.className = 'chart-card';
  note.style.color = '#475569';
  note.style.fontSize = '.82rem';
  note.style.lineHeight = '1.5';
  note.textContent = reason;
  wrap.appendChild(note);
  scrollToBottom();
}

function renderChart(wrap, data) {
  if (!data || !data.values || data.values.length < 2) return;

  const dir   = data.trend_direction || 'STABLE';
  const color = dir === 'INCREASING' ? '#ef4444' : dir === 'DECREASING' ? '#16a34a' : '#6366f1';
  const arrow = dir === 'INCREASING' ? '↑' : dir === 'DECREASING' ? '↓' : '→';
  const cls   = dir === 'INCREASING' ? 'chart-trend-up' : dir === 'DECREASING' ? 'chart-trend-down' : 'chart-trend-stable';
  const pct   = (data.pct_change >= 0 ? '+' : '') + data.pct_change + '%';

  // Built with DOM APIs rather than innerHTML, deliberately.
  //
  // `display_name` and `unit` come from ParsedLabValue rows, which are populated
  // from uploaded PDFs, Kanta XML and LLM parsing output — attacker-influenced
  // text with no escaping anywhere in that chain. A unit column carrying an
  // image tag with an error handler reached innerHTML here and executed on a
  // page that holds the CSRF token in scope. (The payload is deliberately not
  // written out: this comment is served to the browser, and apps/accounts/
  // test_appsec.py scans the rendered page for exactly that string.)
  //
  // textContent is used instead of escapeHtml() + innerHTML so the escaping
  // cannot be forgotten by a later edit: there is no HTML-parsing path to
  // forget it on. See apps/rag_assistant/test_chart_xss.py.
  const card = document.createElement('div');
  card.className = 'chart-card';

  const header = document.createElement('div');
  header.className = 'chart-card-header';

  const titleEl = document.createElement('span');
  titleEl.className = 'chart-card-title';
  titleEl.textContent = `📈 ${data.display_name} · ${data.unit}`;

  const trendEl = document.createElement('span');
  trendEl.className = cls;
  trendEl.textContent = `${arrow} ${pct} over ${data.labels.length} readings`;

  header.appendChild(titleEl);
  header.appendChild(trendEl);

  const canvasWrap = document.createElement('div');
  canvasWrap.className = 'chart-canvas-wrap';
  const canvasEl = document.createElement('canvas');
  canvasEl.id = `chart-${Date.now()}`;
  canvasWrap.appendChild(canvasEl);

  card.appendChild(header);
  card.appendChild(canvasWrap);

  const bubble = wrap.querySelector('.bubble-assistant');
  if (bubble) bubble.after(card);
  else wrap.appendChild(card);

  const canvas = card.querySelector('canvas');

  // ── Guard against unit-mismatch scale distortion ─────────────────────────
  // Only show a reference line if it's within 5× of the actual data range.
  const dataMin = Math.min(...data.values);
  const dataMax = Math.max(...data.values);
  const dataRange = Math.max(dataMax - dataMin, dataMax * 0.05, 0.001);
  const scale5x  = dataMax * 5;

  const rawLow  = data.reference_low  != null ? data.reference_low  : null;
  const rawHigh = data.reference_high != null ? data.reference_high : null;
  const refLow  = (rawLow  != null && rawLow  < scale5x) ? rawLow  : null;
  const refHigh = (rawHigh != null && rawHigh < scale5x) ? rawHigh : null;

  // Y-axis bounds: fit data + small padding; include ref lines if they're sane
  const candidates = [dataMin, dataMax];
  if (refLow  != null) candidates.push(refLow);
  if (refHigh != null) candidates.push(refHigh);
  const yMin = Math.min(...candidates) - dataRange * 0.15;
  const yMax = Math.max(...candidates) + dataRange * 0.15;

  // Point colours: red if above high ref, orange if below low ref, else match trend
  const ptColors = data.values.map(v => {
    if (refHigh != null && v > refHigh) return '#ef4444';
    if (refLow  != null && v < refLow)  return '#f59e0b';
    return color;
  });

  const datasets = [{
    label: data.display_name,
    data:  data.values,
    borderColor: color,
    backgroundColor: color + '18',
    borderWidth: 2.5,
    pointRadius: 5,
    pointHoverRadius: 7,
    pointBackgroundColor: ptColors,
    pointBorderColor: ptColors,
    tension: 0.35,
    fill: true,
  }];

  if (refHigh != null) {
    datasets.push({
      label: 'Upper limit',
      data: data.labels.map(() => refHigh),
      borderColor: '#fbbf24',
      borderWidth: 1.5,
      borderDash: [5, 4],
      pointRadius: 0,
      fill: false,
    });
  }
  if (refLow != null) {
    datasets.push({
      label: 'Lower limit',
      data: data.labels.map(() => refLow),
      borderColor: '#94a3b8',
      borderWidth: 1.5,
      borderDash: [4, 4],
      pointRadius: 0,
      fill: false,
    });
  }

  new Chart(canvas, {
    type: 'line',
    data: { labels: data.labels, datasets },
    options: {
      responsive: true,
      maintainAspectRatio: false,
      plugins: {
        legend: { display: datasets.length > 1, labels: { font: { size: 10 }, boxWidth: 14 } },
        tooltip: {
          callbacks: { label: ctx => `${ctx.dataset.label}: ${ctx.parsed.y} ${data.unit}` },
        },
      },
      scales: {
        x: { ticks: { font: { size: 10 }, maxRotation: 45 }, grid: { display: false } },
        y: {
          min: yMin,
          max: yMax,
          ticks: { font: { size: 10 }, callback: v => v + (data.unit ? ' ' + data.unit : '') },
          grid: { color: '#f1f5f9' },
        },
      },
    },
  });
}

function copyMsg(btn) {
  const bubble = btn.closest('.bubble-assistant');
  const text = bubble.getAttribute('data-raw');
  navigator.clipboard.writeText(text).then(() => {
    btn.setAttribute('aria-label', 'Copied!');
    btn.innerHTML = hcIcon('check');
    setTimeout(() => {
      btn.setAttribute('aria-label', 'Copy message');
      btn.innerHTML = hcIcon('copy');
    }, 1500);
  });
}

