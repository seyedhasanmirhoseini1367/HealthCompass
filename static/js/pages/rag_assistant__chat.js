// Assistant text is untrusted: it is generated by an external model from
// retrieved document content, so it can contain HTML — including HTML an
// uploaded document talked the model into echoing. marked() passes raw HTML
// straight through to innerHTML, so neutralise markup BEFORE rendering.
// Markdown itself still works: only literal tags are defanged.
function escapeHtml(s) {
  return String(s == null ? '' : s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

// Separate from escapeHtml because it is used INSIDE an attribute value.
// escapeHtml stays exactly as it was: it runs over the whole message before
// parsing, and widening it there would change how ordinary quotes in an answer
// are rendered and double-escape URLs that legitimately contain them.
function escapeAttr(s) {
  return escapeHtml(s).replace(/"/g, '&quot;');
}

// The one rule for whether a URL may become a clickable target.
//
// Resolution against location.origin is deliberate: it means a relative
// "/records/1" and a protocol-relative "//evil.example" are both judged as the
// absolute URL the browser would actually navigate to, rather than by how they
// look. Anything that is not http(s) after that — javascript:, data:, vbscript:,
// and every casing of them — is refused.
function safeUrl(raw, sameOriginOnly) {
  if (!raw) return null;
  try {
    const parsed = new URL(raw, location.origin);
    if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:') return null;
    if (sameOriginOnly && parsed.origin !== location.origin) return null;
    return parsed.href;
  } catch (e) {
    return null;   // unparseable URL — not a link
  }
}

// escapeHtml cannot defend the hrefs marked builds for itself.
//
// It runs BEFORE parsing, so it neutralises literal <a> tags in the model's
// output — but `[click](javascript:alert(1))` contains no markup to escape. The
// anchor does not exist yet; marked constructs it afterwards, from text that
// survived escaping untouched. Verified against the bundled marked 12.0.2:
// without this override that input renders <a href="javascript:alert(1)">.
//
// Images are refused outright rather than validated. Nothing in an assistant
// answer needs one — charts go through renderChart and citations through
// renderSources — and an <img> is fetched without the reader doing anything, so
// an attacker-chosen src is an exfiltration channel on sight, whatever its
// protocol. The alt text is rendered as plain text instead.
const _mdRenderer = new marked.Renderer();

_mdRenderer.link = function (href, title, text) {
  const safe = safeUrl(href);
  if (!safe) return text;          // no anchor at all; the label survives as text
  const external = !safe.startsWith(location.origin + '/');
  return '<a href="' + escapeAttr(safe) + '"'
       + (title ? ' title="' + escapeAttr(title) + '"' : '')
       + (external ? ' target="_blank" rel="noopener noreferrer"' : '')
       + '>' + text + '</a>';
};

_mdRenderer.image = function (href, title, text) {
  return escapeHtml(text || '');
};

marked.use({ renderer: _mdRenderer });

function renderMarkdown(text) {
  return marked.parse(escapeHtml(text));
}
