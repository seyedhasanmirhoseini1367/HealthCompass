async function renameSession(pk, rowId) {
  document.getElementById('menu-' + pk).classList.remove('open');
  const row   = document.getElementById(rowId);
  const link  = row.querySelector('.session-item');
  const current = link.textContent.trim();
  const title = prompt('Rename chat:', current);
  if (!title || title.trim() === current) return;
  const resp = await fetch(`/assistant/session/${pk}/rename/`, {
    method: 'POST',
    headers: {'Content-Type': 'application/json', 'X-CSRFToken': CSRF},
    body: JSON.stringify({title: title.trim()}),
  });
  const data = await resp.json();
  if (data.ok) {
    link.textContent = data.title.length > 26 ? data.title.substring(0, 26) + '…' : data.title;
  }
}

async function deleteSession(pk, rowId) {
  document.getElementById('menu-' + pk).classList.remove('open');
  openDeleteModal('Delete this chat? This cannot be undone.', async () => {
    const resp = await fetch(`/assistant/session/${pk}/delete/`, {
      method: 'POST',
      headers: {'X-CSRFToken': CSRF},
    });
    const data = await resp.json();
    if (data.ok) {
      const row = document.getElementById(rowId);
      row.remove();
      if (row.classList.contains('active')) {
        // new_session is POST-only now — a GET that creates a row was
        // CSRF-exempt by construction.
        const f = document.createElement('form');
        f.method = 'POST'; f.action = '/assistant/new/';
        const t = document.createElement('input');
        t.type = 'hidden'; t.name = 'csrfmiddlewaretoken'; t.value = CSRF;
        f.appendChild(t); document.body.appendChild(f); f.submit();
      }
    }
  }, 'Delete Chat');
}
